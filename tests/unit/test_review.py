def test_puml_has_classes_and_relationships_section_comments() -> None:
    diagram = _diagram(rel_confidences=[0.5, 0.5, 0.5])
    puml_text = ir_to_puml(diagram)
    lines = puml_text.splitlines()

    classes_idx = lines.index("' --- Classes ---")
    relationships_idx = lines.index("' --- Relationships ---")
    assert classes_idx < relationships_idx


def test_puml_omits_header_by_default() -> None:
    diagram = _diagram(rel_confidences=[0.5, 0.5, 0.5])
    puml_text = ir_to_puml(diagram)
    assert "Generated by" not in puml_text


def test_puml_header_names_the_model_when_requested() -> None:
    diagram = _diagram(rel_confidences=[0.5, 0.5, 0.5])
    puml_text = ir_to_puml(diagram, model_id="test/model-x")
    assert "test/model-x" in puml_text.splitlines()[1]


def test_puml_determinism_still_holds_with_header_and_theme() -> None:
    diagram = _diagram(rel_confidences=[0.5, 0.1, 0.5])
    first = ir_to_puml(diagram, model_id="test/model", include_theme=True)
    second = ir_to_puml(diagram, model_id="test/model", include_theme=True)
    assert first == second
